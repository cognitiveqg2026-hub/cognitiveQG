# Tables 24/25
A=[("oracle_vs_noise","Oracle--Noise"),("oracle_vs_vanilla","Oracle--Vanilla"),("noise_vs_vanilla","Noise--Vanilla")]
B=[("oracle_vs_baseline","Oracle--Baseline"),("noise_vs_baseline","Noise--Baseline"),("vanilla_vs_baseline","Vanilla--Baseline")]
def pw(kind,label,capname):
    pk,sk=("w_p_holm","w_p_sig") if kind=="w" else ("t_p_holm","t_p_sig")
    L=[r"""\begin{table*}[!t]
\centering
\caption{Pairwise comparisons of question quality across four trace conditions. Each entry reports the paired mean difference in GPT-Sem ($(s-1)/4$), with the Holm-adjusted """+capname+r""" $p$-value in parentheses. Positive differences indicate higher scores for the first condition. Bold entries indicate adjusted $p < .05$. Panel A compares Oracle, Noise, and Vanilla; Panel B compares each condition with Baseline.}
\label{"""+label+r"""}
\footnotesize
\begin{tabular}{lccc}
\hline"""]
    for title,blk in [("Panel A: Comparisons among Oracle, Noise, and Vanilla",A),("Panel B: Comparisons with Baseline",B)]:
        L.append(r"\multicolumn{4}{l}{\textit{"+title+r"}} \\")
        L.append(r"\textbf{Model} & "+" & ".join(r"\textbf{"+n+"}" for _,n in blk)+r" \\")
        L.append(r"\hline")
        for m in M:
            cells=[]
            for c,_ in blk:
                r=C[(c,m)]; sig=r[sk]=="True"
                cells.append(b(f"{sgn(float(r['mean_diff']))} ({pf(float(r[pk]))})",sig))
            L.append(m+" & "+" & ".join(cells)+r" \\")
        L.append(r"\hline")
    L.append(r"""\end{tabular}
\end{table*}""")
    return "\n".join(L)+"\n"
open(str(OUT / "spare_tables" / "table24_pairwise_wilcoxon.tex"),"w").write(pw("w","tab:causation_pairwise","Wilcoxon signed-rank"))
open(str(OUT / "spare_tables" / "table25_pairwise_ttest.tex"),"w").write(pw("t","tab:causation_pairwise_ttest","paired $t$-test"))
