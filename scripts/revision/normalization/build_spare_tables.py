means={(r[0],r[1]):(float(r[3]),float(r[4])) for r in list(csv.reader(open(U+"condition_means_s-1over4.csv")))[1:]}
C={(r['contrast'],r['model']):r for r in csv.DictReader(open(U+"contrasts_s-1over4.csv"))}
def sgn(x,d=3):
    s=f"{abs(x):.{d}f}"; return ("$-$" if x<0 and float(s)!=0 else "+")+s
def pf(p):
    if p<0.001: return "$<$.001"
    if p>=0.995: return "1.00"
    return f"{p:.3f}"[1:]
def b(s,sig): return f"\\textbf{{{s}}}" if sig else s
