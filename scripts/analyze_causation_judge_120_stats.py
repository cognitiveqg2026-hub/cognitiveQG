#!/usr/bin/env python3
"""
Paired statistics for the causation (Vanilla/Baseline/Noise/Oracle) figure
(docs/manuscript/figures/causation_judge_120_FIXED.pdf, as generated by
scripts/plot_causation_judge_120_newbaseline.py).

Backs up that figure with: paired t-tests and Wilcoxon signed-rank tests (both
p-values, both CIs, both effect sizes), Holm-Bonferroni / Benjamini-Hochberg
multiple-comparison correction, and all six pairwise condition contrasts among
Vanilla/Baseline/Noise/Oracle. All six are treated as equally comparable: every
condition is scored by the identical GPT-5.5 judge mechanism and paired at the
same argument level, so comparability does not depend on which pipeline
generated a given condition's underlying model output.

CONDITION SEMANTICS (generation/causation/run_oracle_causation.py,
run_qwen_causation.py, run_gpt_causation.py):
  - Vanilla  = no trace injected (raw argument text only).
  - Oracle   = the true, matching human gold trace injected (--condition gold).
  - Noise    = a mismatched trace injected (--condition noise): the expert
               annotation of the next argument in the run, (i+1) mod N, in the
               same format as Oracle. Same rule for all eight models.
  - Baseline = not a --condition arm of the Vanilla/Noise/Oracle harness. It's
               the model's standard full-pipeline output
               (results/baseline_complete_dev1-12), generated by a separate
               script on a different date. It is scored by the identical
               GPT-5.5 judge mechanism and paired at the same argument level as
               the other three conditions, so contrasts against it are just as
               directly comparable -- pipeline provenance does not affect the
               validity of a paired comparison on the resulting scores.

DATA PAIRING (verified empirically, not assumed): Vanilla/Noise/Oracle live in
two per-half files with a LOCAL, 1-indexed arg_index (1..60, restarting for the
second half); Baseline lives in one pooled file with a GLOBAL, 0-indexed
arg_index (0..119). Confirmed by matching literal argument text at both
endpoints of both halves (dev1-6 arg_index 1/60 <-> baseline arg_index 0/59;
dev7-12 arg_index 1/60 <-> baseline arg_index 60/119):
    global_id = baseline_arg_index                 (baseline file: use as-is)
    global_id = dev1-6_causation_arg_index  - 1     (dev1-6:  1..60 -> 0..59)
    global_id = dev7-12_causation_arg_index + 59    (dev7-12: 1..60 -> 60..119)
This re-indexing is the one functional change versus the source plotting
script (which discards arg_index entirely, since it only ever needs an
unpaired mean per condition).

Normalization is (s-1)/4, matching Section IV-D1's definition of GPT-Sem
and the correlation-analysis pipeline (Table 12, Figs. 2/4). This script
previously used semantic_equivalence/5.0, matching the source figure as it
was rendered at the time; that was an inconsistency with Section IV-D1, not
an intentional alternative convention, and has been corrected here. Note
that this choice of affine rescaling was always mathematically irrelevant to
every paired test p-value and every effect size computed below, since the
rescaling cancels out of paired differences and out of the ratios that
define Cohen's d_z and the rank-biserial correlation -- only the
unstandardized means, differences, SEMs and CI widths changed when this was
fixed (by the exact affine map, mean_new = 1.25*mean_old - 0.25).

Usage:
  python scripts/analyze_causation_judge_120_stats.py
"""

