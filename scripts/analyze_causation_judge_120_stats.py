def load_scored_pairs(path):
    if not os.path.exists(path):
        return None
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)["scored_pairs"]


def per_arg_scores(pairs):
    """{raw_arg_index: mean (s-1)/4}, matching GPT-Sem as defined in Section
    IV-D1. Field-equivalent to plot_causation_judge_120_newbaseline.py:per_arg
    (kept keyed by arg_index, unlike the source, which discards it), except
    for this normalization fix. Rounded to 10 decimals immediately after
    normalization, before any downstream test (Wilcoxon, t-test, d_z, r_rb,
    CIs) -- mathematically equal values (e.g. two arguments both averaging
    to 1/5) can land on different float64 bit patterns depending on which
    arithmetic path produced them ((s-1)/4 vs s/5, or different numbers of
    averaged judge calls per argument), which breaks exact ties for
    scipy.stats.wilcoxon's rank/tie-correction and makes its p-value
    sensitive to the choice of affine scale even though the test is
    mathematically scale-invariant. Rounding to 10 dp is well below the
    precision that matters for any reported value (3-4 dp) and restores
    exact-tie detection regardless of which scale produced the number."""
    by = defaultdict(list)
    for pr in pairs or []:
        if pr.get("model_missing") or pr.get("gold_missing"):
            continue
        j = pr.get("judge")
        if not isinstance(j, dict):
            continue
        se = j.get("semantic_equivalence")
        if se is None:
            continue
        by[int(pr["arg_index"])].append((se - 1) / 4)
    return {k: round(float(np.mean(v)), 10) for k, v in by.items() if v}


def load_condition_scores(d16_key, d712_key, baseline_key, condition, judge="gpt-5.5"):
    """Return {global_id (0-119): score} for one model/condition on the verified
    global-id scale (baseline's native 0-119 range)."""
    if condition == "baseline":
        path = os.path.join(BASELINE_DIR, baseline_key, JUDGE_BASELINE_FILE[judge])
        return per_arg_scores(load_scored_pairs(path))  # already global 0-119

    slug = JUDGE_CAUSATION_SLUG[judge]
    suffix = "_%s" % slug if slug else ""
    if condition == "noise":
        p16 = os.path.join(DEV16_DIR, "%s_noise_60args%s_judge.json" % (d16_key, suffix))
        p712 = os.path.join(DEV712_DIR, "%s_noise_v2_60args%s_judge.json" % (d712_key, suffix))
    else:
        p16 = os.path.join(DEV16_DIR, "%s_%s_60args%s_judge.json" % (d16_key, condition, suffix))
        p712 = os.path.join(DEV712_DIR, "%s_%s_60args%s_judge.json" % (d712_key, condition, suffix))

    scores16 = per_arg_scores(load_scored_pairs(p16))
    scores712 = per_arg_scores(load_scored_pairs(p712))

    out = {}
    for arg_idx, score in scores16.items():
        out[arg_idx - 1] = score
    for arg_idx, score in scores712.items():
        out[arg_idx + 59] = score
    return out


