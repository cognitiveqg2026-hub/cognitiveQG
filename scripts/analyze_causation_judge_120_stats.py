def bootstrap_ci(x, y, statistic_fn, n_boot=10000, alpha=0.05, seed=42):
    """Seeded percentile bootstrap CI for a paired bivariate statistic (house style)."""
    rng = np.random.default_rng(seed)
    n = len(x)
    boot_vals = np.empty(n_boot)
    for i in range(n_boot):
        idx = rng.integers(0, n, n)
        boot_vals[i] = statistic_fn(x[idx], y[idx])
    lo, hi = np.nanpercentile(boot_vals, [100 * alpha / 2, 100 * (1 - alpha / 2)])
    return float(lo), float(hi)


def shapiro_test(values, alpha=0.05):
    w, p = stats.shapiro(values)
    return {"W": float(w), "p": float(p), "normal_at_alpha": bool(p > alpha)}


def holm_bonferroni(pvals, alpha=0.05):
    """Step-down Holm correction. Returns (adjusted_p, reject) in ORIGINAL order."""
    pvals = np.asarray(pvals, dtype=float)
    m = len(pvals)
    order = np.argsort(pvals)
    sorted_p = pvals[order]
    adj_sorted = np.empty(m)
    running_max = 0.0
    for i in range(m):
        val = min((m - i) * sorted_p[i], 1.0)
        running_max = max(running_max, val)
        adj_sorted[i] = running_max
    adj = np.empty(m)
    adj[order] = adj_sorted
    return adj, adj <= alpha


def benjamini_hochberg(pvals, alpha=0.05):
    """Step-up BH-FDR correction. Returns (adjusted_p, reject) in ORIGINAL order."""
    pvals = np.asarray(pvals, dtype=float)
    m = len(pvals)
    order = np.argsort(pvals)
    sorted_p = pvals[order]
    adj_sorted = np.empty(m)
    running_min = 1.0
    for i in range(m - 1, -1, -1):
        val = min((m / (i + 1)) * sorted_p[i], 1.0)
        running_min = min(running_min, val)
        adj_sorted[i] = running_min
    adj = np.empty(m)
    adj[order] = adj_sorted
    return adj, adj <= alpha


def paired_ttest_with_ci(x, y, alpha=0.05):
    diffs = np.asarray(x) - np.asarray(y)
    n = len(diffs)
    mean_diff = float(np.mean(diffs))
    std_diff = float(np.std(diffs, ddof=1))
    sem_diff = std_diff / math.sqrt(n) if n > 0 else float("nan")
    t_stat, p = stats.ttest_rel(x, y)
    t_crit = stats.t.ppf(1 - alpha / 2, df=n - 1)
    ci = (mean_diff - t_crit * sem_diff, mean_diff + t_crit * sem_diff)
    d_z = mean_diff / std_diff if std_diff > 0 else float("nan")
    return {
        "n": n, "mean_diff": mean_diff,
        "t": float(t_stat), "p": float(p),
        "ci95": ci, "cohens_dz": d_z,
    }


def wilcoxon_with_effect(x, y):
    """Paired Wilcoxon signed-rank test + matched-pairs rank-biserial correlation,
    computed directly from signed ranks of the non-zero differences (not currently
    implemented anywhere in this repo)."""
    x = np.asarray(x)
    y = np.asarray(y)
    diffs = x - y
    nonzero = diffs[diffs != 0]
    n_nonzero = len(nonzero)
    if n_nonzero < 4:
        return {"n_nonzero": n_nonzero, "W": float("nan"), "p": float("nan"),
                "rank_biserial_r": float("nan")}
    ranks = stats.rankdata(np.abs(nonzero))
    w_pos = float(ranks[nonzero > 0].sum())
    w_neg = float(ranks[nonzero < 0].sum())
    r_rb = (w_pos - w_neg) / (w_pos + w_neg)
    try:
        stat, p = stats.wilcoxon(x, y)
        stat, p = float(stat), float(p)
    except ValueError:
        stat, p = float("nan"), float("nan")
    return {"n_nonzero": n_nonzero, "W": stat, "p": p, "rank_biserial_r": float(r_rb)}


