def _json_default(o):
    if isinstance(o, np.integer):
        return int(o)
    if isinstance(o, np.floating):
        return float(o)
    if isinstance(o, np.bool_):
        return bool(o)
    if isinstance(o, np.ndarray):
        return o.tolist()
    raise TypeError("Object of type %s is not JSON serializable" % type(o))


def write_outputs(condition_rows, contrast_rows, metadata, out_dir, stem):
    os.makedirs(out_dir, exist_ok=True)
    cm_path = os.path.join(out_dir, "%s_condition_means.csv" % stem)
    ct_path = os.path.join(out_dir, "%s_contrasts.csv" % stem)
    json_path = os.path.join(out_dir, "%s_summary.json" % stem)
    md_path = os.path.join(out_dir, "%s_report.md" % stem)

    pd.DataFrame(condition_rows).to_csv(cm_path, index=False)

    ct_full = [{col: row.get(col) for col in CONTRAST_COLUMNS} for row in contrast_rows]
    pd.DataFrame(ct_full).to_csv(ct_path, index=False)

    summary = {
        "metadata": metadata,
        "condition_means": condition_rows,
        "contrasts": contrast_rows,
    }
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2, default=_json_default)

    report_text = format_report(summary)
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(report_text)

    return {"condition_means_csv": cm_path, "contrasts_csv": ct_path,
            "json": json_path, "md": md_path}, report_text


def format_report(summary):
    meta = summary["metadata"]
    cond_rows = summary["condition_means"]
    contrast_rows = summary["contrasts"]

    lines = []
    lines.append("=" * 104)
    lines.append("CAUSATION JUDGE (120-ARG, 8-MODEL) -- PAIRED STATISTICS REPORT")
    lines.append("Source figure: %s" % meta["source_figure"])
    lines.append("alpha=%.2f | bootstrap n=%d (seed=%d) | low-coverage threshold n<%d" % (
        meta["alpha"], meta["n_bootstrap"], meta["bootstrap_seed"], meta["low_coverage_n"]))
    lines.append("=" * 104)
    lines.append("")

    lines.append("CONDITION MEANS vs. PUBLISHED FIGURE")
    lines.append("-" * 104)
    lines.append("%-10s %-10s %5s %8s %8s %8s %10s %8s" % (
        "Model", "Condition", "n", "mean", "SEM", "pub.", "diff", "status"))
    for r in cond_rows:
        lines.append("%-10s %-10s %5d %8.3f %8.3f %8.3f %10.4f %8s" % (
            r["model"], r["condition"], r["n"], r["mean"], r["sem"],
            r["published_mean"], r["diff_vs_published"], r["validation_status"]))
    n_pass = sum(1 for r in cond_rows if r["validation_status"] == "PASS")
    lines.append("")
    lines.append("  Validation: %d/%d condition means PASS" % (n_pass, len(cond_rows)))
    lines.append("")

    lines.append("CONTRASTS (all six condition pairs; every condition is scored by the identical")
    lines.append("GPT-5.5 judge mechanism and paired at the same argument level, so all are")
    lines.append("directly comparable regardless of which pipeline generated the underlying output)")
    lines.append("-" * 104)
    lines.append("%-20s %-10s %4s %9s   %-28s %9s %7s   %-9s %9s %7s   %4s" % (
        "Contrast", "Model", "n", "mean_diff", "t-test: CI95 / p (Holm/BH)", "d_z", "",
        "Wilcoxon: p (Holm/BH)", "r_rb", "", "lowN"))
    for row in contrast_rows:
        if row.get("skipped"):
            lines.append("%-20s %-10s %4d   (skipped: n<4)" % (row["contrast"], row["model"], row["n"]))
            continue
        ci_txt = "[%+.3f,%+.3f] p=%.4f" % (row["ttest_ci95_lo"], row["ttest_ci95_hi"], row["ttest_p"])
        holm_bh_t = "H=%.3f/BH=%.3f" % (row["ttest_p_holm"], row["ttest_p_fdr_bh"])
        holm_bh_w = "H=%.3f/BH=%.3f" % (row["wilcoxon_p_holm"], row["wilcoxon_p_fdr_bh"])
        lines.append("%-20s %-10s %4d %+9.3f   %-28s %9.3f %7s   p=%-6.4f %-9s %7.3f %7s   %4s" % (
            row["contrast"], row["model"], row["n"], row["mean_diff"],
            ci_txt, row["cohens_dz"], "",
            row["wilcoxon_p"], holm_bh_w, row["rank_biserial_r"], "",
            "LOW" if row["low_coverage"] else ""))
        lines.append("    %-20s t-test Holm/BH: %s | shapiro(diff) p=%.3f%s" % (
            "", holm_bh_t, row["shapiro_diff_p"],
            "" if row["shapiro_diff_normal_at_alpha"] else "  [diffs non-normal -> favor Wilcoxon]"))
    lines.append("")

    lines.append("NOTES")
    lines.append("-" * 104)
    for note in meta["notes"]:
        lines.append("  - " + note)
    lines.append("")
    lines.append("=" * 104)
    return "\n".join(lines)


