def compute_condition_means_table(data, tol):
    rows = []
    for disp, _, _, _ in MODELS:
        for cond in CONDITIONS:
            scores = np.array(list(data[disp][cond].values()))
            n = len(scores)
            mean = float(scores.mean()) if n else float("nan")
            # ddof=0, matching the source figure's own error-bar formula exactly
            sem = float(scores.std(ddof=0) / math.sqrt(n)) if n > 1 else float("nan")
            pub = PUBLISHED_CONDITION_MEANS[disp][cond]
            diff = mean - pub
            status = "PASS" if abs(diff) <= tol else "FAIL"
            rows.append({
                "model": disp, "condition": cond, "n": n,
                "mean": mean, "sem": sem,
                "published_mean": pub, "diff_vs_published": diff,
                "validation_status": status,
            })
    return rows


def compute_contrasts_table(data, alpha, n_boot, seed, low_cov_n):
    results = {}
    for name, cond_x, cond_y in CONTRASTS:
        for disp, _, _, _ in MODELS:
            sx, sy = data[disp][cond_x], data[disp][cond_y]
            common = sorted(set(sx) & set(sy))
            n = len(common)
            key = (name, disp)
            if n < 4:
                results[key] = {"model": disp, "contrast": name,
                                 "n": n, "skipped": True}
                continue
            x = np.array([sx[k] for k in common])
            y = np.array([sy[k] for k in common])
            tt = paired_ttest_with_ci(x, y, alpha)
            wx = wilcoxon_with_effect(x, y)
            boot_lo, boot_hi = bootstrap_ci(x, y, lambda a, b: np.mean(a) - np.mean(b),
                                             n_boot=n_boot, alpha=alpha, seed=seed)
            shap = shapiro_test(x - y, alpha)
            results[key] = {
                "model": disp, "contrast": name, "skipped": False,
                "n": n,
                "mean_x": float(x.mean()), "mean_y": float(y.mean()),
                "mean_diff": tt["mean_diff"],
                "ttest_t": tt["t"], "ttest_p": tt["p"],
                "ttest_ci95_lo": tt["ci95"][0], "ttest_ci95_hi": tt["ci95"][1],
                "cohens_dz": tt["cohens_dz"],
                "bootstrap_ci95_lo": boot_lo, "bootstrap_ci95_hi": boot_hi,
                "wilcoxon_W": wx["W"], "wilcoxon_p": wx["p"],
                "rank_biserial_r": wx["rank_biserial_r"], "n_nonzero_diffs": wx["n_nonzero"],
                "shapiro_diff_W": shap["W"], "shapiro_diff_p": shap["p"],
                "shapiro_diff_normal_at_alpha": shap["normal_at_alpha"],
                "low_coverage": n < low_cov_n,
            }

    # Within-contrast correction, across models
    for name, _, _ in CONTRASTS:
        keys = [(name, disp) for disp, _, _, _ in MODELS if not results[(name, disp)].get("skipped")]
        if not keys:
            continue
        t_ps = [results[k]["ttest_p"] for k in keys]
        w_ps = [results[k]["wilcoxon_p"] for k in keys]
        t_holm, t_holm_rej = holm_bonferroni(t_ps, alpha)
        t_bh, t_bh_rej = benjamini_hochberg(t_ps, alpha)
        w_holm, w_holm_rej = holm_bonferroni(w_ps, alpha)
        w_bh, w_bh_rej = benjamini_hochberg(w_ps, alpha)
        for i, k in enumerate(keys):
            results[k].update({
                "ttest_p_holm": float(t_holm[i]), "ttest_p_holm_reject": bool(t_holm_rej[i]),
                "ttest_p_fdr_bh": float(t_bh[i]), "ttest_p_fdr_bh_reject": bool(t_bh_rej[i]),
                "wilcoxon_p_holm": float(w_holm[i]), "wilcoxon_p_holm_reject": bool(w_holm_rej[i]),
                "wilcoxon_p_fdr_bh": float(w_bh[i]), "wilcoxon_p_fdr_bh_reject": bool(w_bh_rej[i]),
            })

    # Global correction across every computed test (stricter supplementary view)
    all_keys = [k for k in results if not results[k].get("skipped")]
    if all_keys:
        t_ps_all = [results[k]["ttest_p"] for k in all_keys]
        w_ps_all = [results[k]["wilcoxon_p"] for k in all_keys]
        t_holm_g, t_holm_g_rej = holm_bonferroni(t_ps_all, alpha)
        w_holm_g, w_holm_g_rej = holm_bonferroni(w_ps_all, alpha)
        for i, k in enumerate(all_keys):
            results[k]["ttest_p_holm_global"] = float(t_holm_g[i])
            results[k]["ttest_p_holm_global_reject"] = bool(t_holm_g_rej[i])
            results[k]["wilcoxon_p_holm_global"] = float(w_holm_g[i])
            results[k]["wilcoxon_p_holm_global_reject"] = bool(w_holm_g_rej[i])

    rows = []
    for name, _, _ in CONTRASTS:
        for disp, _, _, _ in MODELS:
            rows.append(results[(name, disp)])
    return rows


